function cleanBrief(text) {
  let t = text.trim();
  const junk = t.search(/\n{3,}/);
  if (junk > 0) t = t.slice(0, junk);
  t = t.replace(/\nAbout Us[\s\S]*$/i, '').trim();
  return t;
}

function getBrief(oil) {
  const key = OIL_ALIASES[oil] || oil.trim();
  const text = briefs[key];
  if (!text) {
    console.warn('Missing brief for', key);
    return `BRIEF\nAroma Tales extrait de parfum inspired by ${oil.trim()}.\n\nConcentration: 40% (Extrait De Parfum).`;
  }
  return cleanBrief(text);
}

